# ---------------------------------------------------------------- quoting
def ps_str(s: str) -> str:
    """PowerShell single-quoted string literal."""
    return "'" + s.replace("'", "''") + "'"


def _join_ps(parts: list[str]) -> str:
    if not parts:
        return "''"
    if len(parts) == 1:
        return parts[0]
    return "(" + " + ".join(parts) + ")"


# ------------------------------------------------------- var expansion
_ENV_RE = re.compile(r"%([A-Za-z_][A-Za-z0-9_]*)%")
_DELAYED_RE = re.compile(r"!([A-Za-z_][A-Za-z0-9_]*)!")
_ARG_RE = re.compile(r"%~([fdpnxsat$]*)([0-9*])", re.IGNORECASE)
_PLAIN_ARG_RE = re.compile(r"%([0-9*])")
_TILDE_ENV_RE = re.compile(r"%~([fdpnxsat$]*)([A-Za-z_][A-Za-z0-9_]*)%", re.IGNORECASE)


def _loop_ref_re() -> re.Pattern[str]:
    return re.compile(r"%(%)?~([fdpnxsat$]*)([A-Za-z])", re.IGNORECASE)


_LOOP_RE = re.compile(r"%%~([fdpnxsat$]*)([A-Za-z])|%%([A-Za-z])|%([A-Za-z])", re.IGNORECASE)


def script_mod_expr(mods: str) -> str:
    """PS expression for %~<mods>0 (script path)."""
    m = (mods or "").lower()
    if m in ("",):
        return "$PSCommandPath"
    if m == "dp":
        return "((Split-Path -Parent $PSCommandPath) + '\\')"
    if m == "nx":
        return "(Split-Path -Leaf $PSCommandPath)"
    if m == "f":
        return "$PSCommandPath"
    if m == "n":
        return "[System.IO.Path]::GetFileNameWithoutExtension($PSCommandPath)"
    if m == "x":
        return "[System.IO.Path]::GetExtension($PSCommandPath)"
    if m == "d":
        return "(([System.IO.Path]::GetPathRoot($PSCommandPath)).TrimEnd('\\'))"
    if m == "p":
        return (
            "((Split-Path -Parent $PSCommandPath) | ForEach-Object { "
            "if ($_.EndsWith('\\')) { $_.Substring(([System.IO.Path]::GetPathRoot($_)).Length - 1) } "
            "else { $_.Substring(([System.IO.Path]::GetPathRoot($_)).Length - 1) + '\\' } })"
        )
    if m == "dp":
        return (
            "((Split-Path -Parent $PSCommandPath) | ForEach-Object { "
            "if ($_.EndsWith('\\')) { $_ } else { $_ + '\\' } })"
        )
    if m in ("dpn", "dpnx", "nxs", "nx"):
        # compose common combos
        if "d" in m and "p" in m and "n" in m and "x" in m:
            return (
                "((Split-Path -Parent $PSCommandPath) + '\\' + (Split-Path -Leaf $PSCommandPath))"
            )
        if "d" in m and "p" in m and "n" in m:
            return "((Split-Path -Parent $PSCommandPath) + '\\' + [System.IO.Path]::GetFileNameWithoutExtension($PSCommandPath))"
        if "n" in m and "x" in m:
            return "(Split-Path -Leaf $PSCommandPath)"
    raise ProfileError("BP012", f"unsupported %~ modifier '%~{mods}0'", 0, PROFILE)


def arg_mod_expr(mods: str, idx: int, lineno: int) -> str:
    """PS expression for %~<mods>N (call/script args; ``%*`` handled upstream)."""
    m = mods or ""
    base = (
        f"$(if ($script:__bat_args.Count -gt {idx - 1}) "
        f"{{ $script:__bat_args[{idx - 1}] }} else {{ '' }})"
    )
    if not m:
        return base
    ml = m.lower()
    if ml == "~":
        # '%~1' arrives here as mods='~'? handled by regex variant; strip quotes
        return f"({base}.Trim('\"'))"
    short = ml.lstrip("~")
    if short == "":
        return f"({base}.Trim('\"'))"
    # generic: resolve full path then derive parts
    expr = base
    if "f" in short or "d" in short or "p" in short or "n" in short or "x" in short:
        full = f"([System.IO.Path]::GetFullPath({expr}))"
        if short == "f":
            return full
        if short == "d":
            return (
                f"(({full} | ForEach-Object {{ [System.IO.Path]::GetPathRoot($_) }}).TrimEnd('\\'))"
            )
        if short == "p":
            return (
                f"(([System.IO.Path]::GetDirectoryName({full})) | ForEach-Object {{ "
                "if ($_.EndsWith('\\')) { $_.Substring(([System.IO.Path]::GetPathRoot($_)).Length - 1) } "
                "else { $_.Substring(([System.IO.Path]::GetPathRoot($_)).Length - 1) + '\\' } })"
            )
        if short == "n":
            return f"([System.IO.Path]::GetFileNameWithoutExtension({full}))"
        if short == "x":
            return f"([System.IO.Path]::GetExtension({full}))"
        if short in ("dp", "pd"):
            return (
                f"((Split-Path -Parent ([System.IO.Path]::GetFullPath({expr}))) | ForEach-Object {{ "
                "if ($_.EndsWith('\\')) { $_ } else { $_ + '\\' } })"
            )
        if short in ("nx", "xn"):
            return f"(Split-Path -Leaf {full})"
    raise ProfileError("BP012", f"unsupported arg modifier '%~{mods}{idx}'", lineno, PROFILE)


def loop_mod_expr(psvar: str, mods: str, lineno: int) -> str:
    """PS expression applying %~mods to a loop variable value.

    Supported subset (v0.1): f d p dp n x nx f-combos dpn dpnx.
    Anything else raises BP012.
    """
    m = (mods or "").lower()
    if m == "":
        return psvar
    for c in m:
        if c not in "fdpnx":
            raise ProfileError("BP012", f"unsupported for-modifier '%%~{mods}'", lineno, PROFILE)
    full = f"([System.IO.Path]::GetFullPath([string]{psvar}))"
    base = full if ("f" in m or "d" in m or "p" in m) else psvar
    key = "".join(sorted(c for c in m if c in "dpnx"))
    if key == "f":
        return full
    if key == "d":
        return f"(([System.IO.Path]::GetPathRoot({full})).TrimEnd('\\'))"
    if key == "p":
        return (
            f"(([System.IO.Path]::GetDirectoryName({full})) | ForEach-Object {{ "
            "if ($_.EndsWith('\\')) { $_.Substring(([System.IO.Path]::GetPathRoot($_)).Length - 1) } "
            "else { $_.Substring(([System.IO.Path]::GetPathRoot($_)).Length - 1) + '\\' } })"
        )
    if key == "dp":
        return (
            f"((Split-Path -Parent {full}) | ForEach-Object {{ "
            "if ($_.EndsWith('\\')) { $_ } else { $_ + '\\' } })"
        )
    if key == "n":
        return f"([System.IO.Path]::GetFileNameWithoutExtension([string]{base}))"
    if key == "x":
        return f"([System.IO.Path]::GetExtension([string]{base}))"
    if key == "nx":
        return f"(Split-Path -Leaf ([System.IO.Path]::GetFullPath([string]{base})))"
    if key == "dpn":
        return (
            f"((Split-Path -Parent {full}) | ForEach-Object {{ "
            "if ($_.EndsWith('\\')) { $_ } else { $_ + '\\' } } | ForEach-Object { "
            f"$_ + [System.IO.Path]::GetFileNameWithoutExtension([string]{base}) }})"
        )
    if key == "dpnx":
        return full
    raise ProfileError("BP012", f"unsupported for-modifier '%%~{mods}'", lineno, PROFILE)


def translate_text(
    text: str,
    loop_vars: dict[str, str],
    lineno: int = 0,
    allow_nondet: bool = True,
    keep_carets: bool = False,
    delayed: bool = True,
) -> str:
    """Translate a batch word/sentence to a PS string expression.

    Handles ``%%x``/``%x`` loop refs (with ``~`` modifiers), ``%0..%9``,
    ``%*``, ``%~dp0``-family, ``%VAR%``, ``!VAR!``, ``%ERRORLEVEL%``,
    ``%CD%`` and ``%%`` escapes. Everything else is literal.

    With ``keep_carets=True`` caret escapes are preserved literally (for
    text re-parsed by cmd, e.g. ``cmd /c`` children). With
    ``allow_nondet=False`` ``%DATE%``/``%TIME%``/``%RANDOM%`` (both spellings)
    raise :class:`_NondetVar` so the caller can fall back to cmd expansion.
    With ``delayed=False`` (script never enables delayed expansion)
    ``!VAR!`` is literal text, matching cmd.
    """
    parts: list[str] = []
    lit: list[str] = []
    i = 0
    n = len(text)

    def flush() -> None:
        if lit:
            parts.append(ps_str("".join(lit)))
            lit.clear()

    while i < n:
        ch = text[i]
        # Caret escape: the next char is literal (this also suppresses %/!
        # expansion). With keep_carets the escape is preserved for cmd.
        if ch == "^" and i + 1 < n:
            if keep_carets:
                lit.append("^")
            lit.append(text[i + 1])
            i += 2
            continue
        # double-percent loop refs (%%x / %%~..x). Single-% names (%VAR%,
        # %1, %x) are handled below so env vars like %PATH% win over a loop
        # variable named 'p'.
        if ch == "%" and text.startswith("%%", i):
            m = _LOOP_RE.match(text, i)
            if m and m.group(0).startswith("%%"):
                if m.group(0).startswith("%%~"):
                    # %%~modsL form: re-parse '%%~<mods><letter>'
                    inner = m.group(0)[3:]  # after %%~
                    letter = inner[-1]
                    mods = inner[:-1]
                    key = letter.lower()
                    if key in loop_vars:
                        flush()
                        parts.append(loop_mod_expr(loop_vars[key], mods, lineno))
                    else:
                        lit.append(m.group(0)[1:])
                    i = m.end()
                    continue
                lv = m.group(3)
                if lv is not None:
                    key = lv.lower()
                    if key in loop_vars:
                        flush()
                        parts.append(loop_vars[key])
                    else:
                        # '%%' outside a loop collapses to literal '%'
                        lit.append("%" + lv)
                    i = m.end()
                    continue
        # script args %~..N / %N / %*
        if ch == "%" and i + 1 < n:
            ma = _ARG_RE.match(text, i)
            if ma:
                mods, num = ma.group(1), ma.group(2)
                flush()
                if num == "*":
                    parts.append("($script:__bat_args -join ' ')")
                elif num == "0":
                    if mods:
                        parts.append(script_mod_expr(mods))
                    else:
                        parts.append("$PSCommandPath")
                else:
                    parts.append(arg_mod_expr(mods, int(num), lineno))
                i = ma.end()
                continue
            mp = _PLAIN_ARG_RE.match(text, i)
            if mp:
                num = mp.group(1)
                flush()
                if num == "*":
                    parts.append("($script:__bat_args -join ' ')")
                elif num == "0":
                    parts.append("$PSCommandPath")
                else:
                    parts.append(arg_mod_expr("", int(num), lineno))
                i = mp.end()
                continue
            # %~modsVAR% (e.g. %~dp0 handled above as num 0; others rare)
            mt = _TILDE_ENV_RE.match(text, i)
            if mt:
                mods, name = mt.group(1), mt.group(2)
                flush()
                parts.append(f"$env:{name}")
                i = mt.end()
                continue
            me = _ENV_RE.match(text, i)
            if me:
                name = me.group(1)
                flush()
                up = name.upper()
                if up == "ERRORLEVEL":
                    parts.append("$LASTEXITCODE")
                elif up == "CD":
                    parts.append("((Get-Location).Path)")
                elif up in ("DATE", "TIME", "RANDOM"):
                    if not allow_nondet:
                        raise _NondetVar(name)
                    if up == "RANDOM":
                        parts.append("(Get-Random -Minimum 0 -Maximum 32768)")
                    elif up == "DATE":
                        parts.append("(Get-Date -Format 'ddd MM/dd/yyyy')")
                    else:
                        parts.append("(Get-Date -Format 'HH:mm:ss.ff')")
                else:
                    parts.append(f"$env:{name}")
                i = me.end()
                continue
            # stray '%' or '%%' escape
            if text.startswith("%%", i):
                lit.append("%")
                i += 2
                continue
            # single-% loop ref (%x) for command-line style bodies; only when
            # the letter is a bound loop var (env vars were matched above).
            if (
                i + 1 < n
                and text[i + 1].isalpha()
                and text[i + 1].lower() in loop_vars
                and (i + 2 >= n or (not text[i + 2].isalnum() and text[i + 2] != "_"))
            ):
                flush()
                parts.append(loop_vars[text[i + 1].lower()])
                i += 2
                continue
            lit.append(ch)
            i += 1
            continue
        if ch == "!" and i + 1 < n:
            if not delayed:
                lit.append(ch)
                i += 1
                continue
            md = _DELAYED_RE.match(text, i)
            if md:
                name = md.group(1)
                flush()
                up = name.upper()
                if up == "ERRORLEVEL":
                    parts.append("$LASTEXITCODE")
                elif up == "CD":
                    parts.append("((Get-Location).Path)")
                elif up in ("DATE", "TIME", "RANDOM"):
                    if not allow_nondet:
                        raise _NondetVar(name)
                    if up == "RANDOM":
                        parts.append("(Get-Random -Minimum 0 -Maximum 32768)")
                    elif up == "DATE":
                        parts.append("(Get-Date -Format 'ddd MM/dd/yyyy')")
                    else:
                        parts.append("(Get-Date -Format 'HH:mm:ss.ff')")
                else:
                    parts.append(f"$env:{name}")
                i = md.end()
                continue
            lit.append(ch)
            i += 1
            continue
        lit.append(ch)
        i += 1
    flush()
    return _join_ps(parts)


class _NondetVar(Exception):
    pass


def contains_nondet(text: str) -> bool:
    up = text.upper()
    for tok in ("%DATE%", "%TIME%", "%RANDOM%", "!DATE!", "!TIME!", "!RANDOM!"):
        if tok in up:
            return True
    return False


# ------------------------------------------------------- for/f options
def parse_forf_options(options: str) -> dict[str, Any]:
    """Parse for /f option string into tokens/delims/skip/eol/usebackq."""
    opt = (options or "").strip()
    tokens: list[object] = [1]
    delims = " \t"
    skip = 0
    eol: str | None = ";"
    usebackq = False
    if opt == "":
        return {"tokens": tokens, "delims": delims, "skip": skip, "eol": eol, "usebackq": False}
    # usebackq may appear bare
    parts = opt.split()
    if any(p.lower() == "usebackq" for p in parts):
        usebackq = True
    # eol=<c> | eol= (none)
    m = re.search(r"eol=(.)?", opt, re.IGNORECASE)
    eol = m.group(1) if m else (";" if "eol" not in opt.lower() else None)
    m = re.search(r"skip=(\d+)", opt, re.IGNORECASE)
    if m:
        skip = int(m.group(1))
    m = re.search(r'delims=([^\s"]*)', opt)
    if m:
        raw = m.group(1)
        delims = raw.replace("\\t", "\t").replace("\\n", "\n")
        # 'delims=' with empty value means: no splitting
    elif "delims=" in opt.lower():
        delims = ""
    m = re.search(r"tokens=([0-9,\-\*]+)", opt, re.IGNORECASE)
    if m:
        tokens = parse_tokens_spec(m.group(1))
    elif "tokens=*" in opt.lower().replace(" ", ""):
        tokens = ["*"]
    return {"tokens": tokens, "delims": delims, "skip": skip, "eol": eol, "usebackq": usebackq}


def parse_tokens_spec(spec: str) -> list[object]:
    out: list[object] = []
    for piece in spec.split(","):
        piece = piece.strip()
        if piece == "*":
            out.append("*")
        elif "-" in piece:
            a, _, b = piece.partition("-")
            try:
                lo, hi = int(a), int(b)
            except ValueError:
                raise ProfileError("BP000", f"bad tokens spec {spec!r}", 0, PROFILE) from None
            out.extend(range(lo, hi + 1))
        else:
            try:
                out.append(int(piece))
            except ValueError:
                raise ProfileError("BP000", f"bad tokens spec {spec!r}", 0, PROFILE) from None
    # dedupe preserving order
    seen: list[object] = []
    for t in out:
        if t not in seen:
            seen.append(t)
    return seen


def split_inset(raw: str) -> list[str]:
    """Split for-in item set on space/comma/semicolon, quote-aware."""
    items: list[str] = []
    cur: list[str] = []
    in_q = False
    i = 0
    n = len(raw)
    while i < n:
        ch = raw[i]
        if ch == "^" and i + 1 < n:
            cur.append(ch)
            cur.append(raw[i + 1])
            i += 2
            continue
        if ch == '"':
            in_q = not in_q
            cur.append(ch)
            i += 1
            continue
        if not in_q and ch in (" ", "\t", ",", ";"):
            if cur:
                items.append("".join(cur))
                cur = []
            i += 1
            continue
        cur.append(ch)
        i += 1
    if cur:
        items.append("".join(cur))
    return items


# ------------------------------------------------------- passthrough
_NEEDS_EXPAND_PCT0 = re.compile(r"%~[fdpnxsat$]*0|%0", re.IGNORECASE)
_NEEDS_EXPAND_ERR = re.compile(r"%ERRORLEVEL%", re.IGNORECASE)


def _needs_expand(text: str, loop_vars: dict[str, str]) -> bool:
    """True when a cmd-bound line must be PS-expanded before spawning cmd.

    Raw ``cmd /c`` text is byte-perfect except for three cases: bound loop
    refs (``%%x`` would print literally), ``%0``-family (a ``/c`` string has
    no script path) and ``%ERRORLEVEL%`` (the child starts at 0, not the
    live register). Everything else (``%VAR%``, carets, ``%DATE%``...) is
    expanded by the child itself from the shared environment.
    """
    if loop_vars and "%%" in text:
        # Only when one of the %% pairs names a bound loop var.
        low = text.lower()
        for key in loop_vars:
            if f"%%{key}" in low or f"%{key}" in low:
                return True
    if _NEEDS_EXPAND_PCT0.search(text):
        return True
    return bool(_NEEDS_EXPAND_ERR.search(text))


def _child_lines(
    raw_cmd: str, ctx: _Ctx, ind: str, lineno: int, var: str = "$__bat_cmd"
) -> list[str]:
    """Emit a ``cmd /d /c`` child for an external/piped line.

    Loop refs, ``%0`` and ``%ERRORLEVEL%`` are spliced via PowerShell so the
    child observes the live values; all other ``%``/``^`` forms pass through
    for cmd to expand (identical environment, identical parsing).
    """
    if _needs_expand(raw_cmd, ctx.loop_vars):
        try:
            expr = translate_text(
                raw_cmd,
                ctx.loop_vars,
                lineno,
                allow_nondet=False,
                keep_carets=True,
                delayed=ctx.delayed,
            )
        except _NondetVar:
            expr = ""
        if expr:
            return [f"{ind}{var} = ({expr})", f"{ind}& cmd /d /c {var}"]
    s = raw_cmd.replace("'", "''")
    lines = [f"{ind}{var} = '{s}'"]
    lines.append(
        f"{ind}if ({var} -match '(?i)%ERRORLEVEL%') "
        "{ " + var + " = " + var + " -replace '(?i)%ERRORLEVEL%', $LASTEXITCODE.ToString() }"
    )
    lines.append(f"{ind}& cmd /d /c {var}")
    return lines


# ------------------------------------------------------- emitter core
class _Ctx:
    def __init__(self) -> None:
        self.loop_vars: dict[str, str] = {}
        self.depth = 0
        self.in_function = False
        self.delayed = True


def convert(text: str, source_name: str = "input.bat") -> str:
    from .parser import walk_tree

    script = parse_text(text)
    delayed = any(
        isinstance(n, SetLocal)
        and "delayed" in n.options.lower()
        and "disable" not in n.options.lower()
        for n in walk_tree(script.statements)
    )
    em = _Emitter(source_name, delayed)
    return em.emit(script)


def partial_stub(source_name: str, rule_id: str, message: str, lineno: int = 0) -> str:
    """Emit a fail-loud .ps1 backstop for out-of-profile input.

    Used only with ``convert --allow-partial``: the script refuses at RUN
    time with the same BP-id the strict converter reports at CONVERT time.
    """
    head = HEADER.format(ver=__version__, prof=PROFILE, src=source_name)
    safe = message.replace("'", "''")
    loc = f"line {lineno}: " if lineno else ""
    return head + f"Write-Error 'unsupported: {rule_id}: {loc}{safe}'\nexit 2\n"


def _indent(level: int) -> str:
    return "  " * level


def _fold_division(e: str) -> str:
    """Rewrite top-level ``/`` as truncating batch division.

    PowerShell `/` on integers yields doubles (7/2=3.5, [int] rounds to 4);
    batch truncates toward zero (7/2=3). Split on paren-depth-0 slashes and
    fold left through __bat_div.
    """
    parts: list[str] = []
    cur: list[str] = []
    depth = 0
    in_q = False
    i = 0
    n = len(e)
    while i < n:
        ch = e[i]
        if ch == "'":
            in_q = not in_q
            cur.append(ch)
            i += 1
            continue
        if not in_q and ch == "(":
            depth += 1
            cur.append(ch)
            i += 1
            continue
        if not in_q and ch == ")":
            depth = max(0, depth - 1)
            cur.append(ch)
            i += 1
            continue
        if not in_q and depth == 0 and ch == "/":
            parts.append("".join(cur))
            cur = []
            i += 1
            continue
        cur.append(ch)
        i += 1
    parts.append("".join(cur))
    if len(parts) == 1:
        return e
    acc = parts[0]
    for p in parts[1:]:
        # Space-separated call form: f(a,b) would bind ONE array argument.
        acc = f"__bat_div ({acc}) ({p})"
    return acc


class _Emitter:
    def __init__(self, source_name: str, delayed: bool = True) -> None:
        self.source_name = source_name
        self._loop_counter = 0
        self._delayed = delayed

    def _tr(
        self,
        text: str,
        loop_vars: dict[str, str],
        lineno: int = 0,
        allow_nondet: bool = True,
        keep_carets: bool = False,
    ) -> str:
        return translate_text(text, loop_vars, lineno, allow_nondet, keep_carets, self._delayed)

    def _new_ctx(self) -> _Ctx:
        ctx = _Ctx()
        ctx.delayed = self._delayed
        return ctx

    # -- top level -------------------------------------------------
    def emit(self, script: Script) -> str:
        out: list[str] = []
        out.append(HEADER.format(ver=__version__, prof=PROFILE, src=self.source_name))
        call_targets = self._call_targets(script)
        # Validate call-targets contain no goto (BP011)
        label_bodies = self._label_sections(script)
        for target in call_targets:
            if target in label_bodies and self._contains_goto(label_bodies[target]):
                raise ProfileError(
                    "BP011",
                    f"call-target :{target} contains goto (out of profile v0.1)",
                    0,
                    PROFILE,
                )
        for target in sorted(call_targets):
            if target in label_bodies:
                out.extend(self._emit_function(target, label_bodies[target]))
        if script.has_goto or script.has_call_label:
            out.extend(self._emit_state_machine(script, call_targets))
        else:
            ctx = self._new_ctx()
            for st in script.statements:
                if isinstance(st, (Blank, Label)):
                    continue
                out.extend(self._emit_stmt(st, ctx, 0))
        out.append("exit $LASTEXITCODE")
        return "\n".join(out) + "\n"

    def _call_targets(self, script: Script) -> set[str]:
        from .parser import walk_tree

        targets: set[str] = set()
        for st in walk_tree(script.statements):
            if isinstance(st, Call) and st.kind == "label" and st.target != ":EOF":
                targets.add(st.target)
        return targets

    def _label_sections(self, script: Script) -> dict[str, list[object]]:
        sections: dict[str, list[object]] = {}
        current: str | None = None
        order: list[str] = []
        for st in script.statements:
            if isinstance(st, Label):
                current = st.name
                sections.setdefault(current, [])
                if current not in order:
                    order.append(current)
            elif current is not None:
                sections[current].append(st)
        self._label_order = order
        return sections

    def _contains_goto(self, stmts: list[object]) -> bool:
        # 'goto :eof' is a plain return inside subroutines (handled by the
        # function emitter), so only real cross-label jumps count here.
        from .parser import walk_tree

        return any(isinstance(st, Goto) and not st.is_eof for st in walk_tree(stmts))

    def _main_stmts(self, script: Script) -> list[object]:
        out: list[object] = []
        for st in script.statements:
            if isinstance(st, Label):
                break
            out.append(st)
        return out

    # -- functions for call targets --------------------------------
    def _emit_function(self, target: str, body: list[object]) -> list[str]:
        lines = [f"function __bat_sub_{target} {{", "  param([string[]]$SubArgs)"]
        lines.append("  $script:__bat_saved_args = $script:__bat_args")
        lines.append("  $script:__bat_args = @($SubArgs)")
        ctx = self._new_ctx()
        ctx.in_function = True
        for st in body:
            if isinstance(st, (Blank, Label)):
                continue
            if isinstance(st, Goto) and st.is_eof:
                lines.append("  $script:__bat_args = $script:__bat_saved_args")
                lines.append("  return")
                continue
            if isinstance(st, Exit) and not st.is_bare:
                code = (st.code or "0").strip() or "0"
                try:
                    expr = self._tr(code, ctx.loop_vars, st.lineno)
                except _NondetVar as e:
                    raise EmitError(
                        "BP000", f"nondeterministic exit code: {e}", st.lineno, PROFILE
                    ) from None
                lines.append(f"  $LASTEXITCODE = {expr}")
                lines.append("  $script:__bat_args = $script:__bat_saved_args")
                lines.append("  return")
                continue
            lines.extend(self._emit_stmt(st, ctx, 1))
        lines.append("  $script:__bat_args = $script:__bat_saved_args")
        lines.append("}")
        return lines

    # -- state machine ----------------------------------------------
    def _emit_state_machine(self, script: Script, call_targets: set[str]) -> list[str]:
        sections = self._label_sections(script)
        order: list[str] = getattr(self, "_label_order", list(sections.keys()))
        lines = [
            "$script:__bat_next = '__main'",
            "while ($true) {",
        ]
        # __main section
        lines.append("  if ($script:__bat_next -eq '__main') {")
        lines.append("    $script:__bat_next = $null")
        ctx = self._new_ctx()
        for st in self._main_stmts(script):
            if isinstance(st, (Blank, Label)):
                continue
            lines.extend(self._emit_guarded(st, ctx, 2))
        if order:
            lines.append(
                "    if (-not $script:__bat_next) { $script:__bat_next = '" + order[0] + "' }"
            )
        else:
            lines.append("    if (-not $script:__bat_next) { break }")
        lines.append("  }")
        for idx, name in enumerate(order):
            nxt = order[idx + 1] if idx + 1 < len(order) else None
            lines.append(f"  elseif ($script:__bat_next -eq '{name}') {{")
            lines.append("    $script:__bat_next = $null")
            for st in sections[name]:
                if isinstance(st, (Blank, Label)):
                    continue
                lines.extend(self._emit_guarded(st, ctx, 2))
            if nxt:
                lines.append(f"    if (-not $script:__bat_next) {{ $script:__bat_next = '{nxt}' }}")
            else:
                lines.append("    if (-not $script:__bat_next) { break }")
            lines.append("  }")
        lines.append(
            '  else { Write-Error ("bat2ps: unknown label \'" + $script:__bat_next + "\'"); exit 3 }'
        )
        lines.append("}")
        return lines

    def _emit_guarded(self, st: object, ctx: _Ctx, level: int) -> list[str]:
        """Emit a section statement guarded so a pending jump skips the rest."""
        ind = _indent(level)
        # Unconditional jumps need no guard wrapper for themselves, but the
        # *following* statements do. We emit every statement after the first
        # inside an `if (-not ...)` guard by wrapping each one individually.
        inner = self._emit_stmt(st, ctx, level + 1)
        if not inner:
            return []
        head = f"{ind}if (-not $script:__bat_next) {{"
        tail = f"{ind}}}"
        return [head] + inner + [tail]

    # -- statements --------------------------------------------------
    def _emit_stmt(self, st: object, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        if isinstance(st, (Blank, Rem)):
            return []
        if isinstance(st, Label):
            return []
        if isinstance(st, Echo):
            return self._emit_echo(st, ctx, ind)
        if isinstance(st, SetLocal):
            return [f"{ind}__bat_PushScope"]
        if isinstance(st, EndLocal):
            return [f"{ind}__bat_PopScope"]
        if isinstance(st, SetAssign):
            return self._emit_set_assign(st, ctx, ind)
        if isinstance(st, SetArith):
            return self._emit_set_arith(st, ctx, ind)
        if isinstance(st, SetDisplay):
            return self._emit_set_display(st, ctx, ind)
        if isinstance(st, Goto):
            return self._emit_goto(st, ctx, ind)
        if isinstance(st, Call):
            return self._emit_call(st, ctx, ind)
        if isinstance(st, Exit):
            return self._emit_exit(st, ctx, ind)
        if isinstance(st, Cd):
            return self._emit_cd(st, ctx, ind)
        if isinstance(st, Popd):
            return [f"{ind}try {{ Pop-Location -ErrorAction Stop }} catch {{ }}"]
        if isinstance(st, Shift):
            return [
                f"{ind}if ($script:__bat_args.Count -gt 0) "
                "{ $script:__bat_args = @($script:__bat_args | Select-Object -Skip 1) }",
            ]
        if isinstance(st, Title):
            return []
        if isinstance(st, Chcp):
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        if isinstance(st, If):
            return self._emit_wrapped(st, ctx, level)
        if isinstance(st, ForIn):
            return self._emit_wrapped(st, ctx, level)
        if isinstance(st, ForF):
            return self._emit_wrapped(st, ctx, level)
        if isinstance(st, ForL):
            return self._emit_wrapped(st, ctx, level)
        if isinstance(st, Block):
            return self._emit_wrapped(st, ctx, level)
        if isinstance(st, Chain):
            return self._emit_chain(st, ctx, level)
        if isinstance(st, Pipeline):
            return _child_lines(st.raw, ctx, ind, st.lineno)
        if isinstance(st, Redirected):
            return self._emit_redirected(st, ctx, level)
        if isinstance(st, Generic):
            return _child_lines(st.text, ctx, ind, st.lineno)
        raise EmitError("BP000", f"cannot emit {type(st).__name__}", 0, PROFILE)

    def _emit_echo(self, st: Echo, ctx: _Ctx, ind: str) -> list[str]:
        # Verified: echo preserves ERRORLEVEL (never touches it).
        if st.kind in ("off", "on", "noop"):
            return []
        if st.kind == "state":
            # bare 'echo' prints ECHO state; passthrough for exact bytes.
            return _child_lines("echo", ctx, ind, st.lineno)
        if st.kind == "blank":
            return [f"{ind}Write-Output ''"]
        text = st.text
        if contains_nondet(text):
            return _child_lines("echo " + text, ctx, ind, st.lineno)
        try:
            expr = self._tr(text, ctx.loop_vars, st.lineno)
        except _NondetVar:
            return _child_lines("echo " + text, ctx, ind, st.lineno)
        return [f"{ind}Write-Output {expr}"]

    def _emit_set_assign(self, st: SetAssign, ctx: _Ctx, ind: str) -> list[str]:
        name = st.name.strip().strip('"')
        if not re.fullmatch(r"[^\W\d][\w]*", name or "", re.UNICODE):
            raise ProfileError("BP000", f"bad variable name {st.name!r}", st.lineno, PROFILE)
        value = st.value
        # A value of '' clears the var. Verified: set preserves ERRORLEVEL.
        if value == "":
            return [f"{ind}Remove-Item env:{name} -ErrorAction SilentlyContinue"]
        try:
            expr = self._tr(value, ctx.loop_vars, st.lineno)
        except _NondetVar:
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        return [f"{ind}$env:{name} = {expr}"]

    def _emit_set_arith(self, st: SetArith, ctx: _Ctx, ind: str) -> list[str]:
        # Verified: `set /a` is SILENT in batch files and preserves ERRORLEVEL.
        name = st.name
        if not re.fullmatch(r"[^\W\d][\w]*", name or "", re.UNICODE):
            raise ProfileError("BP000", f"bad variable name {name!r}", st.lineno, PROFILE)
        expr = self._translate_arith(st.expr, ctx, st.lineno)
        if st.op == "=":
            calc = expr
        else:
            psop = {
                "+=": "+",
                "-=": "-",
                "*=": "*",
                "/=": "/",
                "%=": "%",
                "&=": "-band",
                "|=": "-bor",
                "^=": "-bxor",
                "<<=": "-shl",
                ">>=": "-shr",
            }[st.op]
            calc = f"(([int]$env:{name}) {psop} ({expr}))"
        calc = _fold_division(calc)
        return [
            f"{ind}$env:{name} = ([string]([int]({calc})))",
        ]

    def _translate_arith(self, expr: str, ctx: _Ctx, lineno: int) -> str:
        # Expand %VAR% / !VAR! to ([int]$env:VAR), then bare identifiers.
        e = expr
        e = _ENV_RE.sub(lambda m: f"([int]$env:{m.group(1)})", e)
        e = _DELAYED_RE.sub(lambda m: f"([int]$env:{m.group(1)})", e)

        # loop vars in arithmetic: %x / %%x
        def loop_sub(m: re.Match[str]) -> str:
            tok = m.group(0)
            letter = tok[-1]
            key = letter.lower()
            if key in ctx.loop_vars:
                return f"([int]{ctx.loop_vars[key]})"
            return tok

        e = _LOOP_RE.sub(loop_sub, e)
        # Batch '~' is bitwise NOT (PS: -bnot).
        e = re.sub(r"~(?=[\w\(\$])", "-bnot ", e)
        # Batch '^' is xor; '<<' '>>' are shifts.
        e = re.sub(r"\^", " -bxor ", e)
        e = re.sub(r"<<", " -shl ", e)
        e = re.sub(r">>", " -shr ", e)

        # Batch leading-0 integers are octal (PS has no octal literals).
        def _oct(m: re.Match[str]) -> str:
            try:
                return str(int(m.group(1), 8))
            except ValueError:
                return m.group(0)

        e = re.sub(r"(?<![\w\$])0([0-7]+)(?![\w])", _oct, e)

        # Bare identifiers (batch allows 'x+=1' without %): map words to env.
        def word_sub(m: re.Match[str]) -> str:
            w = m.group(1)
            if w in ("band", "bor", "bxor", "bnot", "shl", "shr", "int", "env"):
                return w
            # skip if already part of $env: or $__ / $LASTEXITCODE etc.
            return f"([int]$env:{w})"

        e = re.sub(r"(?<![\w$:>])([A-Za-z_][A-Za-z0-9_]*)(?![\w:])", word_sub, e)
        return e

    def _emit_set_display(self, st: SetDisplay, ctx: _Ctx, ind: str) -> list[str]:
        # Verified: `set` preserves ERRORLEVEL; cmd lists matches sorted A-Z.
        if st.prefix == "":
            return [
                f"{ind}Get-ChildItem env: | Sort-Object Name | ForEach-Object "
                "{ Write-Output ($_.Name + '=' + $_.Value) }",
            ]
        try:
            expr = self._tr(st.prefix, ctx.loop_vars, st.lineno)
        except _NondetVar:
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        # 'set PREFIX' lists vars starting with PREFIX (case-insensitive).
        return [
            f"{ind}$__bat_pref = {expr}",
            f"{ind}Get-ChildItem env: | Where-Object {{ $_.Name.StartsWith($__bat_pref, [System.StringComparison]::OrdinalIgnoreCase) }} "
            "| Sort-Object Name | ForEach-Object { Write-Output ($_.Name + '=' + $_.Value) }",
        ]

    def _emit_goto(self, st: Goto, ctx: _Ctx, ind: str) -> list[str]:
        if st.is_dynamic:
            try:
                expr = self._tr(st.target, ctx.loop_vars, st.lineno)
            except _NondetVar as e:
                raise EmitError("BP000", f"bad goto target: {e}", st.lineno, PROFILE) from None
            return [
                f"{ind}$__bat_t = ({expr}).TrimStart(':').ToUpper()",
                f"{ind}if ($__bat_t -eq 'EOF') {{ break }} else {{ $script:__bat_next = $__bat_t }}",
            ]
        if st.is_eof:
            if ctx.in_function:
                return [f"{ind}return"]
            return [f"{ind}break"]
        return [f"{ind}$script:__bat_next = '{st.target}'"]

    def _emit_call(self, st: Call, ctx: _Ctx, ind: str) -> list[str]:
        if st.kind == "label":
            if st.target == ":EOF":
                if ctx.in_function:
                    return [f"{ind}return"]
                return [f"{ind}break"]
            # call args: split respecting quotes, expand each
            arg_exprs: list[str] = []
            if st.args:
                from .lexer import tokenize as _tok

                for tok in _tok(st.args):
                    try:
                        arg_exprs.append(self._tr(tok, ctx.loop_vars, st.lineno))
                    except _NondetVar:
                        return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
            arr = "@(" + ", ".join(arg_exprs) + ")" if arg_exprs else "@()"
            return [f"{ind}__bat_sub_{st.target} {arr}"]
        # file / raw calls run under cmd for byte parity
        return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)

    def _emit_exit(self, st: Exit, ctx: _Ctx, ind: str) -> list[str]:
        if st.is_bare:
            if ctx.in_function:
                return [f"{ind}return"]
            return [f"{ind}break"]
        code = (st.code or "0").strip() or "0"
        try:
            expr = self._tr(code, ctx.loop_vars, st.lineno)
        except _NondetVar:
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        if ctx.in_function:
            return [f"{ind}$LASTEXITCODE = {expr}", f"{ind}return"]
        return [f"{ind}exit {expr}"]

    def _emit_cd(self, st: Cd, ctx: _Ctx, ind: str) -> list[str]:
        if st.pushd:
            if st.path:
                try:
                    expr = self._tr(st.path, ctx.loop_vars, st.lineno)
                except _NondetVar:
                    return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
                return [
                    f"{ind}try {{ Push-Location {expr} -ErrorAction Stop; $LASTEXITCODE = 0 }} "
                    "catch { Write-Output 'The system cannot find the path specified.'; $LASTEXITCODE = 1 }",
                ]
            return [f"{ind}try {{ Push-Location -ErrorAction Stop }} catch {{ }}"]
        if st.path is None:
            # Verified: bare `cd` preserves ERRORLEVEL; prints the cwd.
            return [f"{ind}Write-Output ((Get-Location).Path)"]
        # strip /d flag (PS has no drive restriction)
        p = st.path.strip()
        if p.lower().startswith("/d"):
            p = p[2:].strip()
        try:
            expr = self._tr(p, ctx.loop_vars, st.lineno)
        except _NondetVar:
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        return [
            f"{ind}try {{ Set-Location {expr} -ErrorAction Stop; $LASTEXITCODE = 0 }} "
            "catch { Write-Output 'The system cannot find the path specified.'; $LASTEXITCODE = 1 }",
        ]

    def _emit_wrapped(self, st: object, ctx: _Ctx, level: int) -> list[str]:
        """Emit If/For/Block, wrapping stdout into suffix redirections."""
        ind = _indent(level)
        suffix: tuple[Redir, ...] = getattr(st, "suffix", ())
        if isinstance(st, If):
            core = self._emit_if(st, ctx, level)
        elif isinstance(st, ForIn):
            core = self._emit_for_in(st, ctx, level)
        elif isinstance(st, ForF):
            core = self._emit_for_f(st, ctx, level)
        elif isinstance(st, ForL):
            core = self._emit_for_l(st, ctx, level)
        elif isinstance(st, Block):
            core = self._emit_block(st, ctx, level)
        else:
            raise EmitError("BP000", "cannot wrap", 0, PROFILE)
        if not suffix:
            return core
        return self._wrap_redirections(core, suffix, ctx, ind, 0)

    def _wrap_redirections(
        self, core: list[str], redirs: tuple[Redir, ...], ctx: _Ctx, ind: str, lineno: int
    ) -> list[str]:
        """Route a native core's stdout through clean > / >> redirections."""
        for r in redirs:
            if r.complex or r.op not in (">", ">>") or r.fd not in ("", "1"):
                return _child_lines(
                    "<complex block redirection>", ctx, ind, lineno
                )  # pragma: no cover
        # fd-2 truncations create empty files; stdout routing uses the rest.
        lines = [f"{ind}& {{"] + core
        out_redirs = [r for r in redirs if r.fd in ("", "1")]
        err_truncs = [r for r in redirs if r.fd == "2"]
        if out_redirs:
            # Batch allows at most one stdout target in practice; last wins.
            r = out_redirs[-1]
            dest = self._redir_dest(r, ctx, lineno)
            if dest == "NUL":
                lines.append(f"{ind}}} | Out-Null")
            elif r.op == ">>":
                lines.append(f"{ind}}} | Out-File -Encoding ascii -Append -LiteralPath {dest}")
            else:
                lines.append(f"{ind}}} | Out-File -Encoding ascii -LiteralPath {dest}")
        else:
            lines.append(f"{ind}}} | Out-Null")
        for r in err_truncs:
            dest = self._redir_dest(r, ctx, lineno)
            if dest != "NUL":
                if r.op == ">>":
                    lines.append(
                        f"{ind}if (!(Test-Path -LiteralPath {dest})) "
                        f"{{ New-Item -ItemType File -Path {dest} -Force | Out-Null }}"
                    )
                else:
                    lines.append(
                        f"{ind}if (!(Test-Path -LiteralPath {dest})) "
                        f"{{ New-Item -ItemType File -Path {dest} -Force | Out-Null }} "
                        f"else {{ Clear-Content -LiteralPath {dest} }}"
                    )
        return lines

    def _redir_dest(self, r: Redir, ctx: _Ctx, lineno: int) -> str:
        target = r.target.strip()
        if target.startswith('"') and target.endswith('"') and len(target) >= 2:
            target = target[1:-1]
        if target.upper() == "NUL":
            return "NUL"
        try:
            return self._tr(target, ctx.loop_vars, lineno)
        except _NondetVar as e:
            raise EmitError("BP000", f"bad redirect target: {e}", lineno, PROFILE) from None

    def _emit_block(self, st: Block, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        lines = [f"{ind}& {{"]
        for sub in st.body:
            lines.extend(self._emit_stmt(sub, ctx, level + 1))
        lines.append(f"{ind}}}")
        return lines

    def _emit_chain(self, st: Chain, ctx: _Ctx, level: int) -> list[str]:
        """Emit ``A && B || C & D`` natively (same process, live register).

        Links after the first are guarded by the state-machine jump flag so a
        ``goto`` inside an early link skips the rest (in linear mode the flag
        is $null and the guards always pass).
        """
        ind = _indent(level)
        lines: list[str] = []
        first_op, first_stmt = st.links[0]
        assert first_op == ""
        lines.extend(self._emit_stmt(first_stmt, ctx, level))
        for op, sub in st.links[1:]:
            sub_lines = self._emit_stmt(sub, ctx, level + 1)
            if not sub_lines:
                continue
            lines.append(f"{ind}if (-not $script:__bat_next) {{")
            inner = _indent(level + 1)
            if op == "&&":
                lines.append(f"{inner}if ($LASTEXITCODE -eq 0) {{")
                lines.extend(sub_lines)
                lines.append(f"{inner}}}")
            elif op == "||":
                lines.append(f"{inner}if ($LASTEXITCODE -ne 0) {{")
                lines.extend(sub_lines)
                lines.append(f"{inner}}}")
            else:  # '&'
                lines.extend(sub_lines)
            lines.append(f"{ind}}}")
        return lines

    def _emit_redirected(self, st: Redirected, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        # Complex redirections (<, dups, bad fds) run under cmd verbatim.
        if any(r.complex for r in st.redirs):
            return _child_lines(st.raw, ctx, ind, st.lineno)
        if not st.core_text.strip():
            # Bare `> file`: truncate/create with no command.
            return self._wrap_redirections([], st.redirs, ctx, ind, st.lineno)
        try:
            core = _parse_core(st.core_text, st.lineno, st.raw)
        except ProfileError:
            return _child_lines(st.raw, ctx, ind, st.lineno)
        if isinstance(core, (Generic, Chcp)):
            # External commands: the child owns the redirection.
            return _child_lines(st.raw, ctx, ind, st.lineno)
        if isinstance(core, (Chain, Pipeline)):
            # Should not happen (split order), stay safe via cmd.
            return _child_lines(st.raw, ctx, ind, st.lineno)
        emitted = self._emit_stmt(core, ctx, level)
        # Split stdout routing from stderr-only truncations.
        out_redirs = tuple(r for r in st.redirs if r.fd in ("", "1"))
        err_only = tuple(r for r in st.redirs if r.fd == "2")
        lines: list[str] = []
        if out_redirs:
            lines.extend(self._wrap_redirections(emitted, out_redirs, ctx, ind, st.lineno))
        else:
            lines.extend(emitted)
        if err_only:
            # Native cores emit no stderr; just truncate/touch the targets.
            for r in err_only:
                dest = self._redir_dest(r, ctx, st.lineno)
                if dest != "NUL":
                    if r.op == ">>":
                        lines.append(
                            f"{ind}if (!(Test-Path -LiteralPath {dest})) "
                            f"{{ New-Item -ItemType File -Path {dest} -Force | Out-Null }}"
                        )
                    else:
                        lines.append(
                            f"{ind}if (!(Test-Path -LiteralPath {dest})) "
                            f"{{ New-Item -ItemType File -Path {dest} -Force | Out-Null }} "
                            f"else {{ Clear-Content -LiteralPath {dest} }}"
                        )
        return lines

    def _emit_if(self, st: If, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        cond = self._cond_expr(st, ctx)
        if st.negated:
            cond = f"(-not ({cond}))"
        lines = [f"{ind}if ({cond}) {{"]
        for sub in st.then_body:
            lines.extend(self._emit_stmt(sub, ctx, level + 1))
        if st.else_body:
            lines.append(f"{ind}}} else {{")
            for sub in st.else_body:
                lines.extend(self._emit_stmt(sub, ctx, level + 1))
        lines.append(f"{ind}}}")
        return lines

    def _cond_expr(self, st: If, ctx: _Ctx) -> str:
        if st.cond_kind == "errorlevel":
            return f"($LASTEXITCODE -ge {st.number})"
        if st.cond_kind == "defined":
            v = st.var.strip().strip("%").strip("!")
            return f"(Test-Path 'env:{v}')"
        if st.cond_kind == "exist":
            try:
                expr = self._tr(st.path, ctx.loop_vars, st.lineno)
            except _NondetVar as e:
                raise EmitError("BP000", f"bad if exist path: {e}", st.lineno, PROFILE) from None
            return f"(Test-Path {expr})"
        if st.cond_kind == "numeric":
            try:
                left = self._tr(st.left, ctx.loop_vars, st.lineno)
                right = self._tr(st.right, ctx.loop_vars, st.lineno)
            except _NondetVar as e:
                raise EmitError("BP000", f"bad numeric compare: {e}", st.lineno, PROFILE) from None
            opmap = {
                "equ": "-eq",
                "neq": "-ne",
                "lss": "-lt",
                "leq": "-le",
                "gtr": "-gt",
                "geq": "-ge",
            }
            psop = opmap[st.op.lower()]
            return f"(([int]({left})) {psop} ([int]({right})))"
        # streq: literal compare including quotes
        try:
            left = self._tr(st.left, ctx.loop_vars, st.lineno)
            right = self._tr(st.right, ctx.loop_vars, st.lineno)
        except _NondetVar as e:
            raise EmitError("BP000", f"bad string compare: {e}", st.lineno, PROFILE) from None
        op = "-eq" if st.case_insensitive else "-ceq"
        return f"(({left}) {op} ({right}))"

    # -- for ---------------------------------------------------------
    def _new_loop_var(self, letter: str) -> str:
        self._loop_counter += 1
        return f"$__loop_{letter}_{self._loop_counter}"

    def _emit_for_in(self, st: ForIn, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        psvar = self._new_loop_var(st.var)
        items = split_inset(st.items)
        if not items:
            return []
        try:
            exprs = [self._tr(it, ctx.loop_vars, st.lineno) for it in items]
        except _NondetVar:
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        old = dict(ctx.loop_vars)
        ctx.loop_vars[st.var] = psvar
        lines = [
            f"{ind}$__bat_pats = @({', '.join(exprs)})",
            f"{ind}$__bat_items = @()",
            f"{ind}foreach ($__pat in $__bat_pats) {{",
            f"{ind}  if ($__pat -like '*[*?]*') {{",
            f"{ind}    $__bat_hit = @(Get-ChildItem -Name $__pat -ErrorAction SilentlyContinue)",
            f"{ind}    foreach ($__h in $__bat_hit) {{ $__bat_items += $__h }}",
            f"{ind}  }} else {{ $__bat_items += $__pat }}",
            f"{ind}}}",
            f"{ind}foreach ({psvar} in $__bat_items) {{",
        ]
        for sub in st.body:
            lines.extend(self._emit_stmt(sub, ctx, level + 1))
        lines.append(f"{ind}}}")
        ctx.loop_vars = old
        return lines

    def _emit_for_l(self, st: ForL, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        psvar = self._new_loop_var(st.var)
        try:
            s = self._tr(st.start, ctx.loop_vars, st.lineno)
            e = self._tr(st.step, ctx.loop_vars, st.lineno)
            f = self._tr(st.end, ctx.loop_vars, st.lineno)
        except _NondetVar:
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        old = dict(ctx.loop_vars)
        ctx.loop_vars[st.var] = psvar
        lines = [
            f"{ind}$__l_start = [int]({s})",
            f"{ind}$__l_step = [int]({e})",
            f"{ind}$__l_end = [int]({f})",
            f"{ind}if ($__l_step -ne 0) {{",
            f"{ind}  {psvar} = $__l_start",
            f"{ind}  while ((($__l_step -gt 0) -and ({psvar} -le $__l_end)) -or "
            f"(( $__l_step -lt 0) -and ({psvar} -ge $__l_end))) {{",
        ]
        for sub in st.body:
            lines.extend(self._emit_stmt(sub, ctx, level + 1))
        lines.append(f"{ind}    {psvar} += $__l_step")
        lines.append(f"{ind}  }}")
        lines.append(f"{ind}}}")
        ctx.loop_vars = old
        return lines

    def _emit_for_f(self, st: ForF, ctx: _Ctx, level: int) -> list[str]:
        ind = _indent(level)
        opts = parse_forf_options(st.options)
        tokens = opts["tokens"]
        assert isinstance(tokens, list)
        delims = str(opts["delims"])
        skip = int(opts["skip"])
        eol = opts["eol"]
        usebackq = bool(opts["usebackq"]) or st.usebackq
        letters = [st.var]
        base_ord = ord(st.var)
        for k in range(1, len(tokens)):
            letters.append(chr(base_ord + k))
        psvars = [self._new_loop_var(L) for L in letters]
        old = dict(ctx.loop_vars)
        for var_letter, var_ps in zip(letters, psvars, strict=True):
            ctx.loop_vars[var_letter] = var_ps
        try:
            cap = _capture_lines(st.source, usebackq, ctx, st.lineno, ind)
        except _NondetVar:
            ctx.loop_vars = old
            return _child_lines(st.raw.strip().lstrip("@").strip(), ctx, ind, st.lineno)
        lines = list(cap)
        # Batch for/f always skips blank lines (even with delims= / tokens=*).
        lines.append(f"{ind}$__f_lines = @($__f_lines | Where-Object {{ $_ -ne '' }})")
        lines.append(f"{ind}$__f_skip = {skip}")
        if eol is None:
            lines.append(f"{ind}$__f_eol = $null")
        else:
            lines.append(f"{ind}$__f_eol = {ps_str(str(eol))}")
        lines.append(f"{ind}$__f_n = 0")
        lines.append(f"{ind}foreach ($__f_line in $__f_lines) {{")
        lines.append(f"{ind}  $__f_n++")
        lines.append(f"{ind}  if ($__f_n -le $__f_skip) {{ continue }}")
        lines.append(
            f"{ind}  if (($__f_eol -ne $null) -and ($__f_eol -ne '') -and "
            "([string]$__f_line).StartsWith([string]$__f_eol)) { continue }"
        )
        lines.extend(self._emit_token_split(tokens, delims, psvars, level + 1))
        for sub in st.body:
            lines.extend(self._emit_stmt(sub, ctx, level + 1))
        lines.append(f"{ind}}}")
        ctx.loop_vars = old
        return lines

    def _emit_token_split(
        self, tokens: list[Any], delims: str, psvars: list[str], level: int
    ) -> list[str]:
        ind = _indent(level)
        lines: list[str] = []
        if delims == "":
            # whole line is token 1
            lines.append(f"{ind}$__f_toks = @($__f_line)")
        else:
            # Batch delims are a SET of single chars; consecutive collapse.
            dlit = "".join(delims).replace("'", "''")
            lines.append(
                f"{ind}$__f_toks = @(([string]$__f_line).Split("
                f"'{dlit}'.ToCharArray(), [System.StringSplitOptions]::RemoveEmptyEntries))"
            )
            lines.append(
                f"{ind}if ($__f_toks.Count -eq 1 -and $__f_toks[0] -eq '') {{ $__f_toks = @() }}"
            )
        for pos, tok in enumerate(tokens):
            if pos >= len(psvars):
                break
            pv = psvars[pos]
            if tok == "*":
                # remainder of line after the previous `pos` tokens
                lines.append(f"{ind}$__f_rest = [string]$__f_line")
                lines.append(f"{ind}for ($__f_k = 0; $__f_k -lt {pos}; $__f_k++) {{")
                if delims == "":
                    lines.append(f"{ind}  $__f_rest = ''")
                else:
                    dlit2 = "".join(delims).replace("'", "''")
                    lines.append(f"{ind}  $__f_rest = $__f_rest.TrimStart('{dlit2}'.ToCharArray())")
                    lines.append(f"{ind}  $__f_i = $__f_rest.IndexOfAny('{dlit2}'.ToCharArray())")
                    lines.append(
                        f"{ind}  if ($__f_i -lt 0) {{ $__f_rest = '' }} else "
                        f"{{ $__f_rest = $__f_rest.Substring($__f_i)"
                        f".TrimStart('{dlit2}'.ToCharArray()) }}"
                    )
                lines.append(f"{ind}}}")
                lines.append(f"{ind}if ($__f_rest -eq $null) {{ $__f_rest = '' }}")
                lines.append(f"{ind}{pv} = $__f_rest")
            else:
                k = int(tok) - 1
                lines.append(
                    f"{ind}if ($__f_toks.Count -gt {k}) {{ {pv} = $__f_toks[{k}] }} "
                    f"else {{ {pv} = '' }}"
                )
        return lines


# The capture helper is implemented as a module function to keep _Emitter small.
def _capture_lines(source: str, usebackq: bool, ctx: _Ctx, lineno: int, ind: str) -> list[str]:
    src = source.strip()
    # command form?
    is_cmd = False
    cmd_text = ""
    if (
        src.startswith("'")
        and src.endswith("'")
        and len(src) >= 2
        and not usebackq
        or src.startswith("`")
        and src.endswith("`")
        and len(src) >= 2
        or usebackq
        and src.startswith('"')
        and src.endswith('"')
        and len(src) >= 2
    ):
        is_cmd = True
        cmd_text = src[1:-1]
    if is_cmd:
        if _needs_expand(cmd_text, ctx.loop_vars):
            try:
                expr = translate_text(
                    cmd_text,
                    ctx.loop_vars,
                    lineno,
                    allow_nondet=False,
                    keep_carets=True,
                    delayed=ctx.delayed,
                )
            except _NondetVar:
                expr = ""
            if expr:
                return [
                    f"{ind}$__f_cmd = ({expr})",
                    f'{ind}$__f_lines = @( & cmd /d /c $__f_cmd | ForEach-Object {{ "$" + $_ }} | ForEach-Object {{ $_.Substring(1) }})',
                ]
        s = cmd_text.replace("'", "''")
        return [
            f"{ind}$__f_cmd = '{s}'",
            f"{ind}if ($__f_cmd -match '(?i)%ERRORLEVEL%') "
            "{ $__f_cmd = $__f_cmd -replace '(?i)%ERRORLEVEL%', $LASTEXITCODE.ToString() }",
            f'{ind}$__f_lines = @( & cmd /d /c $__f_cmd | ForEach-Object {{ "$" + $_ }} | ForEach-Object {{ $_.Substring(1) }})',
        ]
    # literal string form: "..." without usebackq
    if src.startswith('"') and src.endswith('"') and len(src) >= 2 and not usebackq:
        try:
            expr = translate_text(src[1:-1], ctx.loop_vars, lineno, delayed=ctx.delayed)
        except _NondetVar:
            raise
        return [f"{ind}$__f_lines = @({expr})"]
    # file set form: one or more paths (space separated), wildcards allowed
    parts = split_inset(src)
    if not parts:
        return [f"{ind}$__f_lines = @()"]
    try:
        exprs = [
            translate_text(p.strip('"'), ctx.loop_vars, lineno, delayed=ctx.delayed) for p in parts
        ]
    except _NondetVar:
        raise
    return [
        f"{ind}$__f_files = @({', '.join(exprs)})",
        f"{ind}$__f_lines = @()",
        f"{ind}foreach ($__ff in $__f_files) {{",
        f"{ind}  if ($__ff -like '*[*?]*') {{",
        f"{ind}    foreach ($__hit in @(Get-ChildItem -Path $__ff -ErrorAction SilentlyContinue)) {{",
        f"{ind}      $__f_lines += @(Get-Content -LiteralPath $__hit.FullName)",
        f"{ind}    }}",
        f"{ind}  }} elseif (Test-Path $__ff) {{",
        f"{ind}    $__f_lines += @(Get-Content -LiteralPath $__ff)",
        f"{ind}  }}",
        f"{ind}}}",
    ]
